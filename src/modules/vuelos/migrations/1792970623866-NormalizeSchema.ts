/**
 * Normalises the schema to third normal form with real foreign keys, keeping the data:
 *  - arrays and jsonb documents become tables (market configuration, offer and hold legs, order history, fraud
 *    reasons, webhook events, roles, passengers, billing identity);
 *  - the order stops copying the trip: its legs come from the booking's hold, its travellers from the offer, its
 *    billing identity is the offer's one (shared row);
 *  - airline names live in `vuelos_aerolineas`, money columns are integers in minor units;
 *  - new tables: invoices (every issued order gets one), the audit trail (events, sagas, request log);
 *  - `ecom_auditoria_cambios` becomes `auditoria_administrativa`.
 * Personal data that was stored encrypted as one document is decrypted and stored field by field, encrypted again
 * with the same key (DATA_ENCRYPTION_KEY, or JWT_SECRET in development). It is a one-way migration: take a backup
 * first (see `down`).
 */

// ---- encryption (same `v1:<iv>:<tag>:<ciphertext>` format as common/cifrado.ts, kept inline on purpose) ----

function resolveKey(): Buffer {
  const raw = process.env.DATA_ENCRYPTION_KEY;
  if (raw) {
    const key = Buffer.from(raw, 'base64');
    if (key.length === 32) return key;
    throw new Error('DATA_ENCRYPTION_KEY must be 32 bytes encoded as base64');
  }
  const secret = process.env.JWT_SECRET ?? '';
  if (process.env.NODE_ENV !== 'production' && secret.length >= 32) {
    return Buffer.from(hkdfSync('sha256', secret, '', 'vuelos-data-encryption', 32));
  }
  throw new Error('There are encrypted rows to convert: set DATA_ENCRYPTION_KEY (the same value the app uses) and run the migration again');
}

const encryptJson = (key: Buffer, value: unknown): string => {
  const iv = randomBytes(12);
  const cipher = createCipheriv('aes-256-gcm', key, iv);
  const data = Buffer.concat([cipher.update(JSON.stringify(value), 'utf8'), cipher.final()]);
  return ['v1', iv.toString('base64'), cipher.getAuthTag().toString('base64'), data.toString('base64')].join(':');
};

const decryptJson = <T>(key: Buffer, payload: string): T => {
  const [, iv, tag, data] = payload.split(':');
  const decipher = createDecipheriv('aes-256-gcm', key, Buffer.from(iv, 'base64'));
  decipher.setAuthTag(Buffer.from(tag, 'base64'));
  return JSON.parse(Buffer.concat([decipher.update(Buffer.from(data, 'base64')), decipher.final()]).toString('utf8')) as T;
};

